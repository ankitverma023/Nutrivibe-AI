def search_food(query: str) -> Optional[Dict]:
    """Finds the closest matching food from the database."""
    if not query:
        return None

    q = query.lower().strip()

    # Exact or alias match
    for item in FOOD_ITEMS:
        if q == item["name"].lower() or q in item["aliases"]:
            return item

    # Partial substring match
    for item in FOOD_ITEMS:
        for alias in item["aliases"]:
            if alias in q or q in alias:
                return item

    # Word intersection match
    q_words = set(q.split())
    best_match = None
    best_score = 0
    for item in FOOD_ITEMS:
        all_terms = " ".join([item["name"]] + item["aliases"]).lower()
        score = sum(1 for w in q_words if len(w) > 2 and w in all_terms)
        if score > best_score:
            best_score = score
            best_match = item

    return best_match
